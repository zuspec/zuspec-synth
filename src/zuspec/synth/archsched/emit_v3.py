"""V3 (stage-TLM) SV classes timed by an architecture schedule.

Same shape as fw-hdl's ``fw.hdl.xls.StageTLM`` classes: per function
``<fn>_stage_tlm`` with ``new(vif, clks_per_op = 0)``, ``clks_per_op``,
``m_clks`` and ``task op(<inputs>, output result)``: the result at zero time
from the SV function, then one ``@(posedge vif.clk)`` per scheduled step.
"""
from __future__ import annotations

import re
from typing import Dict, List, Sequence

from . import xls_ir
from .sched import Schedule


def sv_decl(name: str, ir_type: str, overrides: Dict[str, str]) -> str:
    """``bits[8][4][4] block`` -> ``bit[7:0] block[0:3][0:3]``."""
    if name in overrides:
        return f"{overrides[name]} {name}"
    m = re.fullmatch(r"bits\[(\d+)\]((?:\[\d+\])*)", ir_type.replace(" ", ""))
    if not m:
        raise ValueError(f"emit_v3: cannot map IR type {ir_type!r} of {name} to SV")
    w = int(m.group(1))
    dims = [int(d) for d in re.findall(r"\[(\d+)\]", m.group(2))][::-1]
    return f"bit[{w - 1}:0] {name}" + "".join(f"[0:{d - 1}]" for d in dims)


def _class_sv(orig: xls_ir.Function, s: Schedule, clk_if: str,
              arg_types: Dict[str, str], table: str, consts: Dict[str, int]) -> List[str]:
    fn = orig.sv_path
    cls = fn.split("::")[-1]
    ret_type = next(n.type for n in orig.nodes if n.name == orig.ret) if orig.ret else ""
    args = [f"input {sv_decl(p.name, p.type, arg_types)}" for p in orig.params]
    args.append(f"output {sv_decl('result', ret_type, arg_types)}")
    call = ", ".join(p.name for p in orig.params)
    sp = s.spec
    lines = [
        f"    // {fn} on {sp.arch} ({sp.fold}" + (f" x{sp.unroll}" if sp.unroll else "")
        + f", {sp.sbox_count} {sp.sbox_kind} S-box(es), key expansion {sp.key_expansion}).",
        f"    // Scheduled with " + ", ".join(f"{k}={v}" for k, v in consts.items())
        + " (other values take the same clocks).",
        f"    // latency {s.latency} clk, II {s.ii} (ResMII {s.res_mii}), S-boxes bound "
        f"{s.sbox_count}: " + ", ".join(f"{p} {s.used[p]}" for p in s.used) + ".",
        f"    // Step -> S-box lookups / nodes (full node map: {table}):",
    ]
    per_step: Dict[int, List[xls_ir.Node]] = {}
    for n in s.fn.nodes:
        per_step.setdefault(s.placed[n.name].step, []).append(n)
    for st in range(s.latency):
        ns = per_step.get(st, [])
        sb = [n for n in ns if n.kind == "sbox"]
        binds = ", ".join(f"{n.name}->{s.placed[n.name].pool}[{s.placed[n.name].inst}]"
                          for n in sb[:3]) + (", ..." if len(sb) > 3 else "")
        lines.append(f"    //   step {st}: {len(sb)} S-box, {len(ns)} node(s)"
                     + (f": {binds}" if binds else ""))
    if s.precomputed_sbox_ops:
        lines.append(f"    //   at key load: {s.precomputed_sbox_ops} S-box lookup(s), "
                     f"{len(per_step.get(-1, []))} node(s) incl. constants")
    lines += [
        f"    class {cls}_stage_tlm;",
        f"        static const int unsigned LATENCY  = {s.latency};",
        f"        static const int unsigned II       = {s.ii};",
        f"        static const int unsigned SBOXES   = {s.sbox_count};",
        f"        // One clock per scheduled step (step 0 = load).",
        f"        static const int unsigned CLKS     = LATENCY;",
        f"",
        f"        virtual {clk_if} vif;",
        f"        int unsigned clks_per_op;  // CLKS unless overridden",
        f"        int unsigned m_clks;       // clocks spent in op",
        f"",
        f"        function new(virtual {clk_if} vif, int unsigned clks_per_op = 0);",
        f"            this.vif = vif;",
        f"            this.clks_per_op = (clks_per_op != 0) ? clks_per_op : CLKS;",
        f"        endfunction",
        f"",
        f"        // The result at zero time, then a clock per scheduled step.",
        f"        task op({', '.join(args)});",
        f"            result = {fn}({call});",
        f"            for (int unsigned step = 0; step < clks_per_op; step++) begin",
        f"                @(posedge vif.clk);",
        f"                m_clks++;",
        f"            end",
        f"        endtask",
        f"    endclass",
        f"",
    ]
    return lines


def stage_tlm_sv(items: Sequence, pkg: str, clk_if: str, imports: Sequence[str],
                 arg_types: Dict[str, str], consts: Dict[str, int],
                 task: str = "zuspec.synth.ArchSched") -> str:
    """``items``: (original function, schedule, node-map file name)."""
    archs = sorted({s.spec.arch for _, s, _ in items})
    lines = [f"// Generated by {task} ({', '.join(archs)}). Do not edit.",
             f"interface {clk_if}(input logic clk);",
             f"endinterface",
             f"",
             f"package {pkg};"]
    lines += [f"    import {i}::*;" for i in imports]
    lines.append("")
    for orig, s, table in items:
        lines += _class_sv(orig, s, clk_if, arg_types, table, consts)
    lines.append("endpackage")
    return "\n".join(lines) + "\n"
