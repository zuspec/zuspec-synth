"""Write a lowered :class:`~zuspec.synth.proc.lower.Netlist` as Verilog-2005.

Every operator node of the term DAG becomes one ``wire`` (shared subterms are
written once); registers are one ``always @(posedge clock)`` each with a
synchronous, active-high reset. Plain Verilog keeps the result readable by any
tool (Yosys, Verilator, iverilog) without a SystemVerilog front end.
"""
from __future__ import annotations

from typing import Dict, List, Set

from . import term as T
from .lower import Netlist


def _id(name: str) -> str:
    s = "".join(c if (c.isalnum() or c == "_") else "_" for c in name)
    if not s or s[0].isdigit():
        s = "_" + s
    return s


def _rng(w: int) -> str:
    return f"[{w - 1}:0] " if w > 1 else ""


class _Emitter:
    def __init__(self, nl: Netlist):
        self.nl = nl
        self.names: Dict[T.Term, str] = {}
        self.lines: List[str] = []
        self.n = 0
        self.known: Set[str] = set()

    def ref(self, t: T.Term) -> str:
        if t.op == "const":
            return f"{t.w}'h{t.val:x}"
        if t.op == "var":
            return _id(t.name)
        if t.op == "slice" and t.args[0].op == "var":
            # a slice of a signal is written in place, not as its own wire
            b = t.args[0]
            if b.w == 1:
                return _id(b.name)
            if t.w == 1:
                return f"{_id(b.name)}[{t.val}]"
            return f"{_id(b.name)}[{t.val + t.w - 1}:{t.val}]"
        nm = self.names.get(t)
        if nm is not None:
            return nm
        # children first (iterative, deep terms)
        stack = [(t, False)]
        while stack:
            x, done = stack.pop()
            if x.op in ("const", "var") or x in self.names:
                continue
            if done:
                self._emit_node(x)
            else:
                stack.append((x, True))
                for a in x.args:
                    if a.op not in ("const", "var") and a not in self.names:
                        stack.append((a, False))
        return self.names[t]

    def _emit_node(self, t: T.Term) -> None:
        a = [self.ref(x) for x in t.args]
        op = t.op
        if op == "slice":
            base = t.args[0]
            if base.op == "const":
                expr = f"{t.w}'h{(base.val >> t.val) & ((1 << t.w) - 1):x}"
            elif base.w == 1:
                expr = a[0]
            elif t.w == 1:
                expr = f"{a[0]}[{t.val}]"
            else:
                expr = f"{a[0]}[{t.val + t.w - 1}:{t.val}]"
        elif op == "concat":
            expr = "{" + ", ".join(a) + "}"
        elif op == "not":
            expr = f"~{a[0]}"
        elif op in ("and", "or", "xor"):
            expr = f" {dict(zip(('and', 'or', 'xor'), '&|^'))[op]} ".join(a)
        elif op == "add":
            expr = f"{a[0]} + {a[1]}"
        elif op == "sub":
            expr = f"{a[0]} - {a[1]}"
        elif op == "mul":
            expr = f"{a[0]} * {a[1]}"
        elif op == "eq":
            expr = f"{a[0]} == {a[1]}"
        elif op == "ult":
            expr = f"{a[0]} < {a[1]}"
        elif op == "slt":
            expr = f"$signed({a[0]}) < $signed({a[1]})"
        elif op == "ite":
            expr = f"{a[0]} ? {a[1]} : {a[2]}"
        elif op == "shl":
            expr = f"{a[0]} << {a[1]}"
        elif op == "lshr":
            expr = f"{a[0]} >> {a[1]}"
        elif op == "ashr":
            expr = f"$signed({a[0]}) >>> {a[1]}"
        elif op == "redor":
            expr = f"|{a[0]}"
        elif op == "redand":
            expr = f"&{a[0]}"
        elif op == "redxor":
            expr = f"^{a[0]}"
        else:
            raise ValueError(op)
        self.n += 1
        nm = f"_t{self.n}"
        self.names[t] = nm
        self.lines.append(f"    wire {_rng(t.w)}{nm} = {expr};")


def emit_verilog(nl: Netlist) -> str:
    e = _Emitter(nl)
    out: List[str] = []
    ports = [_id(n) for n, _ in nl.inputs] + [_id(n) for n, _ in nl.outputs]
    out.append(f"// Generated by zuspec.synth.proc from the process lowering of {nl.name}.")
    for r in nl.report:
        out.append(f"//   {r}")
    out.append(f"module {_id(nl.name)} (")
    out.append(",\n".join(f"    {p}" for p in ports))
    out.append(");")
    for n, w in nl.inputs:
        out.append(f"    input  wire {_rng(w)}{_id(n)};")
    for n, t in nl.outputs:
        out.append(f"    output wire {_rng(t.w)}{_id(n)};")
    for r in nl.regs:
        # a process state register keeps the encoding the lowering chose
        attr = '(* fsm_encoding = "none" *) ' if r.origin.startswith("state of ") else ""
        out.append(f"    {attr}reg {_rng(r.w)}{_id(r.name)};    // {r.origin}")
    ports_set = {n for n, _ in nl.inputs} | {n for n, _ in nl.outputs}
    regs_set = {r.name for r in nl.regs}
    for n, t in nl.wires:
        if n in ports_set or n in regs_set:
            continue
        out.append(f"    wire {_rng(t.w)}{_id(n)};")
    for n, w in nl.nets:
        if n in ports_set or n in regs_set:
            continue
        out.append(f"    wire {_rng(w)}{_id(n)};")
    body: List[str] = []
    for n, t in nl.wires:
        body.append(f"    assign {_id(n)} = {e.ref(t)};")
    for n, t in nl.outputs:
        if t.op == "var" and _id(t.name) == _id(n):
            continue
        body.append(f"    assign {_id(n)} = {e.ref(t)};")
    rst = _id(nl.reset) if nl.reset else None
    clk = _id(nl.clock)
    inits: List[str] = []
    for r in nl.regs:
        nxt = e.ref(r.next)
        init = f"{r.w}'h{r.init:x}"
        if rst:
            body.append(f"    always @(posedge {clk}) {_id(r.name)} <= {rst} ? {init} : {nxt};")
            inits.append(f"    initial {_id(r.name)} = {init};")
        else:
            body.append(f"    always @(posedge {clk}) {_id(r.name)} <= {nxt};")
            body.append(f"    initial {_id(r.name)} = {init};")
    if inits:
        # with a reset the initial value only helps simulation before the
        # first reset; synthesis does not get it, so a state register stays
        # an FSM candidate (Yosys skips registers with an initial value)
        body.append("`ifndef SYNTHESIS")
        body.extend(inits)
        body.append("`endif")
    for inst in nl.instances:
        params = ""
        if inst.params:
            params = " #(" + ", ".join(f".{k}({v})" for k, v in inst.params.items()) + ")"
        conns = []
        for c in inst.conns:
            if c.var is not None:
                conns.append(f".{c.port}({_id(c.var.name)})")
            elif c.term is not None:
                conns.append(f".{c.port}({e.ref(c.term)})")
            else:
                conns.append(f".{c.port}()")
        body.append(f"    {inst.module}{params} {_id(inst.name)} (" + ", ".join(conns) + ");")
    out.extend(e.lines)
    out.extend(body)
    out.append("endmodule")
    return "\n".join(out) + "\n"
